#!/usr/bin/env python3
"""Build four actual game styles as isolated16px test tiles in a DDR blob.
SPDX-License-Identifier: GPL-3.0-or-later (generator; original artwork unchanged).
Only the new blob, macro/type header and provenance report are generated.
"""
import argparse
import hashlib
import json
import struct
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ASSETS = (52, 60, 68, 76)
ANCHORS = ((7, 7), (8, 7), (9, 9), (8, 7))
KEY = 0xF81F
MAGIC = 0x31584D50
BASE = 0x009B0000
ATLAS_SHA = '584c47be285778f8680a0f0a5f21a12aa610b3e02b7aa5c58885cedb06b998a6'


def sha(raw):
    return hashlib.sha256(raw).hexdigest()


def crc(raw):
    return zlib.crc32(raw) & 0xFFFFFFFF


def mapped_anchor(anchor, source, target, padding):
    exact = [i for i in range(target) if i * source // target == anchor]
    if exact:
        return (exact[0] + exact[-1]) // 2 + padding
    return min(range(target), key=lambda i: (abs(i * source - anchor * target), i)) + padding


def generate():
    atlas = (ROOT / 'assets/atlas.bin').read_bytes()
    manifest = json.loads((ROOT / 'assets/manifest.json').read_text(encoding='utf-8-sig'))
    if sha(atlas) != ATLAS_SHA or manifest['sha256'].lower() != ATLAS_SHA:
        raise ValueError('Unexpected original game atlas')
    metas, tiles, records = [], [], []
    for style, asset in enumerate(ASSETS):
        s = manifest['sprites'][asset]
        w, h, ax, ay = s['width'], s['height'], s['anchor_x'], s['anchor_y']
        raw = atlas[s['offset']:s['offset'] + w * h * 2]
        png_name = s['source']['source_file']
        png = (ROOT / png_name).read_bytes()
        if sha(raw) != s['rgb565_sha256'] or sha(png) != s['source']['source_sha256']:
            raise ValueError('Actual game source identity changed')
        largest = max(w, h)
        dw, dh = ((w * 16 + largest // 2) // largest,
                  (h * 16 + largest // 2) // largest) if largest > 16 else (w, h)
        px, py = (16 - dw) // 2, (16 - dh) // 2
        source = struct.unpack('<' + 'H' * (w * h), raw)
        output = [KEY] * 256
        for y in range(dh):
            for x in range(dw):
                output[(y + py) * 16 + x + px] = source[(y * h // dh) * w + x * w // dw]
        anchor = (mapped_anchor(ax, w, dw, px), mapped_anchor(ay, h, dh, py))
        if anchor != ANCHORS[style] or output[anchor[1] * 16 + anchor[0]] == KEY:
            raise ValueError('Unexpected adapted physical anchor')
        tile = struct.pack('<256H', *output)
        packed = anchor[0] | anchor[1] << 8 | w << 16 | h << 24
        metas.append(struct.pack('<4I', asset, packed, crc(raw), crc(tile)))
        tiles.append(tile)
        records.append(dict(style=style, source_asset=asset, source_name=s['name'],
            source_style=s['source']['style'], source_width=w, source_height=h,
            source_anchor=[ax, ay], source_atlas_offset=s['offset'],
            source_crc32=f'0x{crc(raw):08X}', source_rgb565_sha256=sha(raw),
            source_png=png_name, source_png_sha256=sha(png),
            resized_width=dw, resized_height=dh, pad_x=px, pad_y=py,
            tile_width=16, tile_height=16, tile_anchor=list(anchor),
            tile_crc32=f'0x{crc(tile):08X}', tile_sha256=sha(tile),
            packed_meta=f'0x{packed:08X}', pixel_offset=80 + style * 512))
    payload = b''.join(metas + tiles)
    blob = struct.pack('<4I', MAGIC, 4, len(payload), crc(payload)) + payload
    assert len(blob) == 2128 and BASE + len(blob) < 0x00A00000
    header = '\n'.join([
        '/* Generated by tools/build_pure_mix16.py; test-only DDR metadata, no SRAM pixel array. */',
        '#ifndef PURE_BULLET_MIX16_H', '#define PURE_BULLET_MIX16_H', '#include <stdint.h>',
        f'#define PURE_MIX_BASE 0x{BASE:08X}U', f'#define PURE_MIX_MAGIC 0x{MAGIC:08X}U',
        '#define PURE_MIX_COUNT 4U', '#define PURE_MIX_BUCKET 500U',
        '#define PURE_MIX_BYTES 2128U', '#define PURE_MIX_PAYLOAD_BYTES 2112U',
        '#define PURE_MIX_META_OFFSET 16U', '#define PURE_MIX_PIXEL_OFFSET 80U',
        f'#define PURE_MIX_PAYLOAD_CRC 0x{crc(payload):08X}U',
        f'#define PURE_MIX_BLOB_CRC 0x{crc(blob):08X}U',
        'typedef struct { uint32_t magic,count,payload_bytes,payload_crc; } PureBulletMixHeader;',
        'typedef struct { uint32_t asset,packed,source_crc,tile_crc; } PureBulletStyleMeta;',
        '_Static_assert(sizeof(PureBulletMixHeader)==16U,"pure mix header ABI");',
        '_Static_assert(sizeof(PureBulletStyleMeta)==16U,"pure mix style ABI");',
        '#endif', '']).encode('utf-8')
    report = dict(schema=1, purpose='isolated four-style same-emitter pure2000 test',
        adapted=True, blob_path='assets/pure_mix16.bin', blob_bytes=len(blob),
        blob_sha256=sha(blob), blob_crc32=f'0x{crc(blob):08X}',
        header_magic=f'0x{MAGIC:08X}', count=4, payload_bytes=len(payload),
        payload_crc32=f'0x{crc(payload):08X}', load_address=f'0x{BASE:08X}',
        meta_offset=16, meta_bytes=16, pixel_offset=80, tile_bytes=512,
        meta_layout='little-endian uint32 asset, packed(anchor_x|anchor_y<<8|source_width<<16|source_height<<24), source_crc32, tile_crc32',
        source_atlas_sha256=sha(atlas), normal_game_atlas_unmodified=True,
        source_png_unmodified=True, key_rgb565='0xF81F', styles=records,
        resize='downscale only; max dimension16; nearest integer dimensions (size*16+largest//2)//largest',
        sampling='srcX=floor(x*source_width/resized_width), srcY=floor(y*source_height/resized_height); exact RGB565 copy',
        padding='floor-centred in16x16; all padding pixels exact0xF81F',
        anchor_mapping='lower midpoint of exact preimage if retained; otherwise minimum absolute rational sampling error, lower index on ties; plus padding',
        source_point_local=[320, 64], source_point_global=[640, 184],
        velocity_q4='vx=((i*17)%49)-24; vy=32',
        activation='10 additional objects before each successfully presented warmup frame; no PURE_START before target reached',
        header_path='src/pure_bullet_mix16.h', header_sha256=sha(header),
        generator_path='tools/build_pure_mix16.py', generator_sha256=sha(Path(__file__).read_bytes()),
        stage9_and_legacy_use_identical_tiles=True, hardware_access=False)
    return {'assets/pure_mix16.bin': blob, 'src/pure_bullet_mix16.h': header,
            'assets/pure_mix16.json': (json.dumps(report, ensure_ascii=False, indent=2) + '\n').encode('utf-8')}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for name, raw in generate().items():
        target = ROOT / name
        if args.check:
            if not target.is_file() or target.read_bytes() != raw:
                raise ValueError('Generated output differs: ' + name)
        else:
            target.write_bytes(raw)
    print('MIX16 ' + ('CHECK PASS' if args.check else 'GENERATED') + ': four actual game styles, DDR-only adapted pixels')


if __name__ == '__main__':
    main()
