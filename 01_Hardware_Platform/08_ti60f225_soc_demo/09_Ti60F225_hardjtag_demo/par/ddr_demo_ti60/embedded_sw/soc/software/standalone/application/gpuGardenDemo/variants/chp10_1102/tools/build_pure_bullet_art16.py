#!/usr/bin/env python3
"""Adapt an actual game projectile for the isolated 2000-instance test.

SPDX-License-Identifier: GPL-3.0-or-later (generator, not user artwork).
Only the generated C header and provenance JSON are written. The normal game
atlas, original PNG, and every other sprite remain byte-for-byte unchanged.
"""
import argparse
import hashlib
import json
import struct
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ASSET = 76
KEY = 0xF81F
ATLAS_SHA256 = '584c47be285778f8680a0f0a5f21a12aa610b3e02b7aa5c58885cedb06b998a6'
SOURCE_PNG = 'assets/source/user_20261016/bullet_09_pink_star.png'
SOURCE_WIDTH, SOURCE_HEIGHT = 21, 20
RESIZED_WIDTH, RESIZED_HEIGHT = 16, 15
TILE_WIDTH, TILE_HEIGHT = 16, 16
PAD_X = (TILE_WIDTH - RESIZED_WIDTH) // 2
PAD_Y = (TILE_HEIGHT - RESIZED_HEIGHT) // 2


def sha(raw):
    return hashlib.sha256(raw).hexdigest()


def crc(raw):
    return zlib.crc32(raw) & 0xFFFFFFFF


def anchor_axis(anchor, source_size, target_size, padding):
    # Use the lower midpoint of the exact nearest-neighbour preimage.
    retained = [x for x in range(target_size) if x * source_size // target_size == anchor]
    if not retained:
        raise ValueError('Source anchor was not retained by the exact resize')
    return (retained[0] + retained[-1]) // 2 + padding


def generate():
    atlas = (ROOT / 'assets/atlas.bin').read_bytes()
    manifest = json.loads((ROOT / 'assets/manifest.json').read_text(encoding='utf-8-sig'))
    if sha(atlas) != ATLAS_SHA256 or manifest['sha256'].lower() != ATLAS_SHA256:
        raise ValueError('Unexpected original game atlas')
    sprite = manifest['sprites'][ASSET]
    if (sprite['id'], sprite['width'], sprite['height'], sprite['anchor_x'], sprite['anchor_y']) != (76, 21, 20, 10, 9):
        raise ValueError('Unexpected actual game pink-star metadata')
    if sprite['source']['source_file'] != SOURCE_PNG:
        raise ValueError('Asset76 does not originate from the actual game pink star')
    png = (ROOT / SOURCE_PNG).read_bytes()
    if sha(png) != sprite['source']['source_sha256']:
        raise ValueError('Original user PNG identity changed')
    source = atlas[sprite['offset']:sprite['offset'] + SOURCE_WIDTH * SOURCE_HEIGHT * 2]
    if sha(source) != sprite['rgb565_sha256']:
        raise ValueError('Actual game RGB565 source differs from manifest')
    pixels = struct.unpack('<' + 'H' * (SOURCE_WIDTH * SOURCE_HEIGHT), source)
    output = [KEY] * (TILE_WIDTH * TILE_HEIGHT)
    for y in range(RESIZED_HEIGHT):
        sy = y * SOURCE_HEIGHT // RESIZED_HEIGHT
        for x in range(RESIZED_WIDTH):
            sx = x * SOURCE_WIDTH // RESIZED_WIDTH
            output[(y + PAD_Y) * TILE_WIDTH + x + PAD_X] = pixels[sy * SOURCE_WIDTH + sx]
    tile = struct.pack('<' + 'H' * len(output), *output)
    anchor = [anchor_axis(sprite['anchor_x'], SOURCE_WIDTH, RESIZED_WIDTH, PAD_X),
              anchor_axis(sprite['anchor_y'], SOURCE_HEIGHT, RESIZED_HEIGHT, PAD_Y)]
    if output[anchor[1] * TILE_WIDTH + anchor[0]] != pixels[sprite['anchor_y'] * SOURCE_WIDTH + sprite['anchor_x']]:
        raise ValueError('Mapped physical anchor pixel changed')
    lines = [
        '/* Generated by tools/build_pure_bullet_art16.py; test-only adaptation.',
        ' * Original game asset76/pink_star 21x20 -> 16x15 + one key padding row.',
        ' * SPDX-License-Identifier: GPL-3.0-or-later (generator; see assets/NOTICE.txt for artwork). */',
        '#ifndef PURE_BULLET_ART16_H', '#define PURE_BULLET_ART16_H', '#include <stdint.h>',
        '#define PURE_ART16_SOURCE_ASSET 76U', '#define PURE_ART16_SOURCE_WIDTH 21U',
        '#define PURE_ART16_SOURCE_HEIGHT 20U', '#define PURE_ART16_SOURCE_ANCHOR_X 10',
        '#define PURE_ART16_SOURCE_ANCHOR_Y 9', '#define PURE_ART16_WIDTH 16U',
        '#define PURE_ART16_HEIGHT 16U', f'#define PURE_ART16_ANCHOR_X {anchor[0]}U',
        f'#define PURE_ART16_ANCHOR_Y {anchor[1]}U',
        f'#define PURE_ART16_SOURCE_CRC 0x{crc(source):08X}U',
        f'#define PURE_ART16_TILE_CRC 0x{crc(tile):08X}U',
        'static const uint16_t pure_art16_pixels[256] = {',
    ]
    for y in range(TILE_HEIGHT):
        lines.append('    ' + ','.join(f'0x{v:04X}U' for v in output[y * 16:(y + 1) * 16]) + ',')
    lines.extend(['};', '#endif', ''])
    header = '\n'.join(lines).encode('utf-8')
    report = {
        'schema': 1, 'purpose': 'isolated pure2000 test only; normal game atlas unchanged',
        'adapted': True, 'source_asset': ASSET, 'source_name': sprite['name'],
        'source_style': sprite['source']['style'], 'source_width': SOURCE_WIDTH,
        'source_height': SOURCE_HEIGHT, 'source_anchor': [sprite['anchor_x'], sprite['anchor_y']],
        'source_atlas_offset': sprite['offset'], 'source_crc32': f'0x{crc(source):08X}',
        'source_rgb565_sha256': sha(source), 'source_atlas_sha256': sha(atlas),
        'source_png': SOURCE_PNG, 'source_png_sha256': sha(png),
        'source_png_unmodified': True, 'normal_game_atlas_unmodified': True,
        'resized_width': RESIZED_WIDTH, 'resized_height': RESIZED_HEIGHT,
        'pad_x': PAD_X, 'pad_y': PAD_Y, 'padding_bottom': 1, 'key_rgb565': '0xF81F',
        'sampling': 'sx=floor(21*x/16), sy=floor(20*y/15); copy exact RGB565 uint16; no filtering/tint/key replacement',
        'padding': 'floor-centred: left0 top0 right0 bottom1; all padding pixels exact key',
        'anchor_mapping': 'lower midpoint of exact source-anchor nearest-neighbour preimage, plus padding',
        'tile_width': TILE_WIDTH, 'tile_height': TILE_HEIGHT, 'tile_anchor': anchor,
        'tile_bytes': len(tile), 'tile_crc32': f'0x{crc(tile):08X}', 'tile_sha256': sha(tile),
        'header_path': 'src/pure_bullet_art16.h', 'header_sha256': sha(header),
        'generator_path': 'tools/build_pure_bullet_art16.py',
        'generator_sha256': sha(Path(__file__).read_bytes()),
        'stage9_and_legacy_use_identical_tile': True, 'hardware_access': False,
    }
    return {'src/pure_bullet_art16.h': header,
            'assets/pure_bullet_art16.json': (json.dumps(report, ensure_ascii=False, indent=2) + '\n').encode('utf-8')}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    outputs = generate()
    for name, raw in outputs.items():
        target = ROOT / name
        if args.check:
            if not target.is_file() or target.read_bytes() != raw:
                raise ValueError('Generated output differs: ' + name)
        else:
            target.write_bytes(raw)
    print('ART16 ' + ('CHECK PASS' if args.check else 'GENERATED') + ': original asset76 -> isolated16x16 tile; original atlas/PNG unchanged')


if __name__ == '__main__':
    main()
