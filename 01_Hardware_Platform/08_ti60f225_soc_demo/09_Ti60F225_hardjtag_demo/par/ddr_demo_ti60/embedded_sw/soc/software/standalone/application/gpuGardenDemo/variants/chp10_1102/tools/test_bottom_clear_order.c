#include "bottom_clear_extracted.inc"

void candidate_model_init(PureBulletParticle *,unsigned,const PureBulletPlan *,const PureBulletRayMeta *,unsigned);
int candidate_model_build(PureBulletParticle *,PureBulletDesc *,uint32_t *,unsigned,uint32_t,const PureBulletPlan *,const PureBulletRayMeta *,unsigned,PureBulletBuildResult *);

static unsigned overlaps(uint32_t a,uint32_t n,uint32_t b,uint32_t m)
{return a<b+m && b<a+n;}

int main(int argc,char **argv)
{
    static const unsigned counts[]={728U,2002U,2093U,2730U};
    static const uint32_t scratch[][2]={
        {G9_DESC0_ADDR,G9_DESC_BYTES},{G9_DESC1_ADDR,G9_DESC_BYTES},
        {G9_ATLAS0_ADDR,G9_ATLAS_BYTES},{G9_ATLAS1_ADDR,G9_ATLAS_BYTES},
        {G9_ROUTE_ADDR,G9_ROUTE_BYTES},{G9_LOG_ADDR,G9_LOG_BYTES}
    };
    if(argc!=2)return 2;
    FILE *f=fopen(argv[1],"rb");if(!f){perror(argv[1]);return 2;}
    uint8_t *blob=malloc(PURE_SCATTER_BYTES);CHECK(blob);
    CHECK(fread(blob,1,PURE_SCATTER_BYTES,f)==PURE_SCATTER_BYTES);fclose(f);
    const PureBulletRayMeta *rays=(const PureBulletRayMeta *)(blob+PURE_SCATTER_RAY_OFFSET);
    const PureBulletPlan *plans=(const PureBulletPlan *)(blob+PURE_SCATTER_PLAN_OFFSET);
    tile_pixels=(uint16_t *)(blob+PURE_SCATTER_PIXEL_OFFSET);
    static PureBulletParticle particles[2730];
    static PureBulletDesc desc[2048];
    unsigned frames_compared=0U;
    for(unsigned ci=0;ci<4U;ci++){
        unsigned count=counts[ci];
        memset(frames,0x5a,sizeof frames);
        candidate_model_init(particles,count,plans,rays,612U);
        for(unsigned frame=0;frame<60U;frame++){
            sel=frame&1U;back_address=sel?FB1_ADDR:FB0_ADDR;
            uint32_t lo=back_address+464U*2560U+320U*2U;
            uint32_t span=135U*2560U+640U*2U;
            CHECK(lo>=back_address && lo+span<=back_address+FB_SIZE_BYTES);
            for(unsigned j=0;j<sizeof scratch/sizeof scratch[0];j++)
                CHECK(!overlaps(lo,span,scratch[j][0],scratch[j][1]));
            PureBulletBuildResult built;
            CHECK(candidate_model_build(particles,desc,&storage.legacy[0].dst,
                count,back_address,plans,rays,612U,&built)==0);
            GardenHud hud={.state="PURE EMITTER TEST",.bullets=count,.peak=count,
                .fps10=601U,.errors=0U,.alpha_supported=1U,.alpha_enabled=1U,.alpha_level=16U};
            path=0U;pixels=frames[path][sel];pending=0U;
            hud_check=1U;garden_ui_hud(&hud);hud_check=0U;
            CHECK(baseline_draw_legacy(back_address,built.legacy_count,count,frame<2U)==0);
            path=1U;pixels=frames[path][sel];reg_status=STATUS_DONE;
            CHECK(begin_bottom_clear(back_address)==0);
            CHECK(ctrl==GPU_CTRL_FILL && dst==lo && width==640U && height==136U && stride==2560U && color==0U);
            pending=1U;reg_status=STATUS_BUSY;async_clears++;
            /* Real particle/descriptor/list writes, whose equality is tested
             * separately, occupy disjoint CPU-only/descriptor DDR ranges. */
            CHECK(finish_bottom_clear()==0 && !pending && reg_status==STATUS_DONE);
            hud_check=1U;garden_ui_hud(&hud);hud_check=0U;
            CHECK(candidate_draw_legacy(back_address,built.legacy_count,count,frame<2U)==0);
            CHECK(!memcmp(frames[0][sel],frames[1][sel],sizeof frames[0][sel]));
            frames_compared++;
        }
        printf("PASS count=%u 60 frames alternating FB0/FB1, complete RGB565 equality, actual stars/tiles/HUD bounds\n",count);
    }
    unsigned before=operations;
    CHECK(begin_bottom_clear(0x123456U)==GPU_ESTATE && operations==before);
    reg_status=STATUS_ERROR;CHECK(finish_bottom_clear()==GPU_EHW);
    reg_status=0U;CHECK(finish_bottom_clear()==GPU_EHW);
    CHECK(async_clears==completed);
    printf("PASS asynchronous lower clear ordering: %u full-frame comparisons, %u starts/completions, %u operations, %u fences; invalid target/error/missing-DONE guards passed\n",
           frames_compared,async_clears,operations,fences);
    free(blob);return 0;
}
