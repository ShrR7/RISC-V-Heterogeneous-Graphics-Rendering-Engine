static void rectangle(unsigned x,unsigned y,unsigned w,unsigned h,uint16_t c)
{
    CHECK(x+w<=1280U && y+h<=720U);
    if(hud_check)CHECK(x>=960U || x+w<=320U || y>=600U || y+h<=464U);
    for(unsigned yy=y;yy<y+h;yy++)for(unsigned xx=x;xx<x+w;xx++)pixels[yy*1280+xx]=c;
}
void garden_render_box(int x,int y,int w,int h,uint16_t c)
{
    CHECK(!pending);CHECK(x>=0 && y>=0 && w>=0 && h>=0);
    rectangle((unsigned)x,(unsigned)y,(unsigned)w,(unsigned)h,c);
}
void garden_render_text_style(int x,int y,const char *text,unsigned style)
{
    /* Conservative whole-glyph cells: if even their bounding rectangles are
     * disjoint from the lower strip, real transparent glyphs also are. */
    unsigned a=style>=GARDEN_TEXT_LARGE_WHITE?16U:8U;
    garden_render_box(x,y,(int)(strlen(text)*a),(int)a,(uint16_t)(0xe7ffU-style));
}
